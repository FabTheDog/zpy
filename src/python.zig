//! Writes the ctypes module of an API collected by `walk`: `runtime.py`
//! followed by declarations.
//!
//! - Error codes become exception classes, raised by `_check`.
//! - Enums become `IntEnum`s.
//! - Values become dataclasses with the Zig field defaults.
//! - Tagged unions become `_Union` classes with one constructor per variant;
//!   a payload whose class is unique to its variant is accepted directly.
//! - Handles become classes wrapping the Zig pointer, released by `close()`,
//!   a `with` block or the garbage collector. A handle implementing an
//!   interface subclasses it.
//! - Every class declares its codec with a decorator, every C function is a
//!   `_fn` entry naming the codecs of its parameters and result.
//! - Functions declared in a type become its methods: instance methods when
//!   the first parameter is the type, `__init__` for a handle's `init`,
//!   static methods otherwise.
//! - Constants of data types become class (or module) attributes.
//! - Every signature is annotated: parameters with what they accept (see
//!   `paramHint`), results with the class they return, so the module
//!   type-checks as a `py.typed` package.

const std = @import("std");
const abi = @import("abi.zig");
const walk = @import("walk.zig");
const source = @import("source.zig");
const Config = @import("bindgen.zig").Config;
const Writer = std.Io.Writer;

pub const Options = struct {
    /// File name of the shared library, next to the generated module.
    lib_file: []const u8,
    /// Parameter names and doc comments, read from the Zig sources.
    docs: *source.Index,
};

pub fn generate(w: *Writer, comptime root: type, comptime cfg: Config, options: Options) Writer.Error!void {
    const g: Gen(root, cfg) = .{ .w = w, .docs = options.docs };
    try g.module(options.lib_file);
}

fn Gen(comptime root: type, comptime cfg: Config) type {
    return struct {
        w: *Writer,
        docs: *source.Index,

        const G = @This();
        const api = walk.collect(root, cfg);

        fn module(g: G, lib_file: []const u8) !void {
            const w = g.w;
            try writeDocstring(w, g.docs.typeDoc(@typeName(root)) orelse "ctypes bindings of a Zig library.", "");
            try w.writeAll("\n# Generated by bindgen from Zig. Do not edit: rebuild instead.\n\n");
            try w.writeAll(@embedFile("runtime.py"));
            try w.print(
                \\
                \\_lib = _c.CDLL(_os.path.join(_os.path.dirname(_os.path.abspath(__file__)), "{s}"))
                \\_abi_hash = _lib.{s}
                \\_abi_hash.argtypes = ()
                \\_abi_hash.restype = _c.c_uint64
                \\if _abi_hash() != 0x{x:0>16}:
                \\    raise ImportError(f"{{_lib._name}} was built from different sources than {{__file__}}: rebuild both")
                \\
                \\# Declaration path -> why it has no binding.
                \\__skipped__: dict[str, str] = {{
                \\
            , .{ lib_file, walk.Api.hashSymbol(cfg), comptime api.hash(cfg) });
            inline for (api.skipped) |s| {
                try w.writeAll("    ");
                try writeString(w, s.path);
                try w.writeAll(": ");
                try writeString(w, s.reason);
                try w.writeAll(",\n");
            }
            try w.writeAll("}\n");

            if (cfg.errors.len > 0) try w.writeAll("\n\n");
            inline for (cfg.errors) |e| try w.print("class {s}(Error): pass\n", .{@errorName(e)});
            if (cfg.errors.len > 0) {
                try w.writeAll("\n_ERRORS.update({");
                inline for (cfg.errors, 1..) |e, i| try w.print("{s}{d}: {s}", .{ if (i > 1) ", " else "", i, @errorName(e) });
                try w.writeAll("})\n");
            }

            inline for (api.types) |t| switch (t.kind) {
                .@"enum" => try g.writeEnum(t),
                .value => try g.writeValue(t),
                .@"union" => try g.writeUnion(t),
                .handle => try g.writeHandle(t),
                else => comptime unreachable,
            };

            try w.writeAll("\n\n");
            inline for (api.functions) |f| try writeFn(w, f);

            try w.writeAll("\n");
            inline for (api.types) |t| if (comptime parentOf(t)) |parent| {
                try w.print("{s}.{s} = {s}\n", .{ parent, comptime lastSegment(t.path), t.name });
            };
            inline for (api.constants) |c| {
                const T = @TypeOf(@field(c.container, c.name));
                if (c.container != root) try w.print("{s}.", .{comptime api.typeName(c.container)});
                try w.print("{f} = ", .{py(c.name)});
                try writeLiteral(w, T, @field(c.container, c.name));
                try w.writeAll("\n");
            }

            inline for (api.functions) |f| if (f.container == root) {
                try w.writeAll("\n\n");
                try g.writeFunction(f, "");
            };
        }

        fn writeEnum(g: G, comptime t: walk.Type) !void {
            const w = g.w;
            const info = @typeInfo(t.T).@"enum";
            try w.print("\n\n@_enum({s})\nclass {s}(_IntEnum):\n", .{ comptime scalarCType(abi.EnumTag(t.T)), t.name });
            _ = try g.writeTypeDoc(t);
            if (info.field_names.len == 0) try w.writeAll("    pass\n");
            inline for (info.field_names, info.field_values) |name, value| {
                try w.print("    {f} = {d}\n", .{ py(name), value });
            }
            try g.writeClassAttrs(t);
            try g.writeMethods(t, true);
        }

        fn writeValue(g: G, comptime t: walk.Type) !void {
            const w = g.w;
            const info = @typeInfo(t.T).@"struct";
            try w.writeAll("\n\n@_value(");
            inline for (info.field_names, info.field_types, 0..) |name, F, i| {
                try w.print("{s}{f}={s}", .{ if (i > 0) ", " else "", py(name), comptime codec(F) });
            }
            const kw_only = comptime isKwOnly(t.T);
            try w.print(")\n@_dc.dataclass{s}\nclass {s}:\n", .{ if (kw_only) "(kw_only=True)" else "", t.name });
            const has_doc = try g.writeTypeDoc(t);
            if (info.field_names.len == 0 and !has_doc and comptime (methodCount(t.T) + classAttrCount(t)) == 0) try w.writeAll("    pass\n");
            inline for (info.field_names, info.field_types, info.field_attrs) |name, F, attrs| {
                try w.print("    {f}: {s}", .{ py(name), comptime hint(F) });
                if (comptime attrs.defaultValue(F)) |default| {
                    try w.writeAll(" = ");
                    if (comptime isMutable(F, default)) {
                        try w.writeAll("_dc.field(default_factory=lambda: ");
                        try writeLiteral(w, F, default);
                        try w.writeAll(")");
                    } else {
                        try writeLiteral(w, F, default);
                    }
                }
                try w.writeAll("\n");
            }
            try g.writeClassAttrs(t);
            try g.writeMethods(t, has_doc or info.field_names.len > 0);
        }

        /// Whether the dataclass of `T` is keyword-only: Python requires
        /// defaulted fields last otherwise.
        fn isKwOnly(comptime T: type) bool {
            var seen_default = false;
            for (@typeInfo(T).@"struct".field_attrs) |attrs| {
                if (attrs.default_value_ptr != null) seen_default = true else if (seen_default) return true;
            }
            return false;
        }

        fn writeUnion(g: G, comptime t: walk.Type) !void {
            const w = g.w;
            const info = @typeInfo(t.T).@"union";
            const Tag = info.tag_type.?;
            try w.print("\n\n@_union({s}", .{comptime scalarCType(abi.EnumTag(Tag))});
            inline for (info.field_names, info.field_types) |name, F| {
                try w.print(", {f}=({d}, {s})", .{ py(name), @backingInt(@field(Tag, name)), comptime codec(F) });
            }
            try w.print(")\nclass {s}(_Union):\n", .{t.name});
            _ = try g.writeTypeDoc(t);
            // The active variant and its payload.
            try w.writeAll("    tag: _Literal[");
            inline for (info.field_names, 0..) |name, i| try w.print("{s}\"{f}\"", .{ if (i > 0) ", " else "", py(name) });
            try w.writeAll("]\n    value: ");
            comptime var has_void = false;
            comptime var n_payloads = 0;
            inline for (info.field_types) |F| {
                if (F == void) {
                    has_void = true;
                } else {
                    try w.print("{s}{s}", .{ if (n_payloads > 0) " | " else "", comptime hint(F) });
                    n_payloads += 1;
                }
            }
            if (has_void) try w.print("{s}None", .{if (n_payloads > 0) " | " else ""});
            try w.writeAll("\n");
            try g.writeClassAttrs(t);
            inline for (info.field_names, info.field_types) |name, F| {
                try w.writeAll("\n");
                switch (comptime abi.kindOf(F)) {
                    .void => try w.print("    @staticmethod\n    def {f}() -> {s}:\n        return {s}(\"{f}\")\n", .{ py(name), t.name, t.name, py(name) }),
                    .value => {
                        // Typed as two overloads: the payload, or its fields.
                        const payload = comptime api.typeName(F);
                        try w.print("    @_overload\n    @staticmethod\n    def {f}(value: {s}, /) -> {s}: ...\n", .{ py(name), payload, t.name });
                        try w.print("    @_overload\n    @staticmethod\n    def {f}(", .{py(name)});
                        try writeFieldParams(w, F);
                        try w.print(") -> {s}: ...\n", .{t.name});
                        try w.print("    @staticmethod\n    def {f}(*args: _Any, **kwargs: _Any) -> {s}:\n        return {s}(\"{f}\", _payload({s}, args, kwargs))\n", .{
                            py(name), t.name, t.name, py(name), payload,
                        });
                    },
                    else => try w.print("    @staticmethod\n    def {f}(value: {s}) -> {s}:\n        return {s}(\"{f}\", value)\n", .{
                        py(name), comptime paramHint(F), t.name, t.name, py(name),
                    }),
                }
            }
            try g.writeMethods(t, true);
        }

        /// The fields of the value `T` as parameters: `name: hint = default`.
        fn writeFieldParams(w: *Writer, comptime T: type) !void {
            const info = @typeInfo(T).@"struct";
            if (comptime isKwOnly(T) and info.field_names.len > 0) try w.writeAll("*, ");
            inline for (info.field_names, info.field_types, info.field_attrs, 0..) |name, F, attrs, i| {
                try w.print("{s}{f}: {s}", .{ if (i > 0) ", " else "", py(name), comptime hint(F) });
                if (comptime attrs.defaultValue(F)) |default| {
                    try w.writeAll(" = ");
                    try writeLiteral(w, F, default);
                }
            }
        }

        /// Nested types and constants assigned to the class after its body,
        /// declared in the body so type checkers know them.
        fn classAttrCount(comptime t: walk.Type) usize {
            var n: usize = 0;
            for (api.types) |nested| if (parentOf(nested)) |parent| {
                if (std.mem.eql(u8, parent, t.name)) n += 1;
            };
            for (api.constants) |c| if (c.container == t.T) {
                n += 1;
            };
            return n;
        }

        fn writeClassAttrs(g: G, comptime t: walk.Type) !void {
            const w = g.w;
            inline for (api.types) |nested| if (comptime parentOf(nested)) |parent| if (comptime std.mem.eql(u8, parent, t.name)) {
                try w.print("    {s}: _ClassVar[type[{s}]]\n", .{ comptime lastSegment(nested.path), nested.name });
            };
            inline for (api.constants) |c| if (c.container == t.T) {
                try w.print("    {f}: _ClassVar[{s}]\n", .{ py(c.name), comptime hint(@TypeOf(@field(c.container, c.name))) });
            };
        }

        fn writeHandle(g: G, comptime t: walk.Type) !void {
            const w = g.w;
            try w.print("\n\n@_handle(\"{s}\"", .{comptime api.destroySymbol(cfg, t.T)});
            const base = if (abi.InterfaceOf(t.T)) |I| comptime api.typeName(I) else "_Handle";
            if (abi.InterfaceOf(t.T)) |I| {
                try w.print(", {{{s}: \"{s}\"}}", .{ comptime api.typeName(I), comptime api.interfaceSymbol(cfg, t.T) });
            }
            try w.print(")\nclass {s}({s}):\n", .{ t.name, base });
            const has_doc = try g.writeTypeDoc(t);
            if (!has_doc and comptime (methodCount(t.T) + classAttrCount(t)) == 0) try w.writeAll("    pass\n");
            try g.writeClassAttrs(t);
            try g.writeMethods(t, has_doc or comptime classAttrCount(t) > 0);
        }

        fn methodCount(comptime T: type) usize {
            var n: usize = 0;
            for (api.functions) |f| n += @intFromBool(f.container == T);
            return n;
        }

        /// `preceded`: whether the class body already has a member.
        fn writeMethods(g: G, comptime t: walk.Type, preceded: bool) !void {
            var sep = preceded;
            inline for (api.functions) |f| if (f.container == t.T) {
                if (sep) try g.w.writeAll("\n");
                sep = true;
                try g.writeFunction(f, "    ");
            };
        }

        /// Writes the doc comment of `t` as a docstring, returns whether there was one.
        fn writeTypeDoc(g: G, comptime t: walk.Type) !bool {
            const doc = g.docs.typeDoc(@typeName(t.T)) orelse return false;
            try writeDocstring(g.w, doc, "    ");
            return true;
        }

        /// The `_fn` entry of `f`.
        fn writeFn(w: *Writer, comptime f: walk.Function) !void {
            const F = @TypeOf(@field(f.container, f.name));
            try w.print("_{s} = _fn(\"{s}\", [", .{ f.symbol, f.symbol });
            inline for (comptime abi.visibleParams(cfg, F), 0..) |P, i| {
                try w.print("{s}{s}", .{ if (i > 0) ", " else "", comptime codec(P) });
            }
            const T = abi.Payload(@typeInfo(F).@"fn".return_type.?);
            if (T == void) try w.writeAll("])\n") else try w.print("], {s})\n", .{comptime codec(T)});
        }

        /// The Python function or method calling the `_fn` entry of `f`.
        fn writeFunction(g: G, comptime f: walk.Function, comptime indent: []const u8) !void {
            const w = g.w;
            const F = @TypeOf(@field(f.container, f.name));
            const style = comptime styleOf(f);
            const params = comptime abi.visibleParams(cfg, F);
            const zig_index = comptime visibleIndices(F);
            const doc = g.docs.fnDoc(@typeName(f.container), f.name);

            var names: [params.len][]const u8 = undefined;
            inline for (&names, 0..) |*name, i| {
                name.* = std.fmt.comptimePrint("arg{d}", .{i});
                if (style == .method and i == 0) {
                    name.* = "self";
                } else if (doc) |d| if (zig_index[i] < d.params.len and !std.mem.eql(u8, d.params[zig_index[i]], "_")) {
                    name.* = d.params[zig_index[i]];
                };
            }
            // Trailing optionals, and values whose fields all have defaults, can be omitted.
            const first_default = comptime firstDefault(params, style);

            if (style == .static) try w.print("{s}@staticmethod\n", .{indent});
            try w.print("{s}def {f}(", .{ indent, py(if (style == .init) "__init__" else comptime snakeCase(f.name)) });
            if (style == .init) try w.writeAll(if (params.len > 0) "self, " else "self");
            inline for (names, params, 0..) |name, P, i| {
                if (i > 0) try w.writeAll(", ");
                if (style == .method and i == 0) {
                    try w.writeAll("self");
                } else if (i >= first_default) {
                    const optional = comptime abi.kindOf(P) == .optional;
                    try w.print("{f}: {s}{s} = None", .{ py(name), comptime paramHint(P), if (optional) "" else " | None" });
                } else {
                    try w.print("{f}: {s}", .{ py(name), comptime paramHint(P) });
                }
            }
            const T = abi.Payload(@typeInfo(F).@"fn".return_type.?);
            try w.print(") -> {s}:\n", .{if (style == .init) "None" else comptime hint(T)});
            if (doc) |d| if (d.doc) |text| try writeDocstring(w, text, indent ++ "    ");
            try w.print("{s}    {s}_{s}(", .{ indent, if (style == .init) "self._adopt(" else "return ", f.symbol });
            for (names, 0..) |name, i| try w.print("{s}{f}", .{ if (i > 0) ", " else "", py(name) });
            try w.writeAll(if (style == .init) "))\n" else ")\n");
        }

        fn styleOf(comptime f: walk.Function) Style {
            if (f.container == root) return .function;
            const F = @TypeOf(@field(f.container, f.name));
            const params = abi.visibleParams(cfg, F);
            if (params.len > 0 and (abi.HandleOf(params[0]) orelse params[0]) == f.container) return .method;
            const T = abi.Payload(@typeInfo(F).@"fn".return_type.?);
            if (T == f.container and abi.kindOf(T) == .handle and std.mem.eql(u8, f.name, "init")) return .init;
            return .static;
        }

        /// Position among all parameters of each visible parameter.
        fn visibleIndices(comptime F: type) [abi.visibleParams(cfg, F).len]usize {
            var indices: [abi.visibleParams(cfg, F).len]usize = undefined;
            var n: usize = 0;
            for (@typeInfo(F).@"fn".param_types, 0..) |P, i| {
                if (abi.isInjected(cfg, P.?)) continue;
                indices[n] = i;
                n += 1;
            }
            return indices;
        }

        /// Python expression of the codec of `T`.
        fn codec(comptime T: type) []const u8 {
            return switch (abi.kindOf(T)) {
                .bool, .int, .float => scalarCType(T),
                .@"enum", .value, .@"union" => api.typeName(T),
                .handle => api.typeName(abi.HandleOf(T).?),
                .optional => "_opt(" ++ codec(@typeInfo(T).optional.child) ++ ")",
                .slice => "_slice(" ++ codec(@typeInfo(T).pointer.child) ++ ")",
                .buffer => "_buffer(" ++ codec(@typeInfo(T).pointer.child) ++ ")",
                .string => "_str",
                .void => "None",
                .unsupported => unreachable,
            };
        }

        /// Type hint of a dataclass field, a union payload or a result.
        fn hint(comptime T: type) []const u8 {
            return switch (abi.kindOf(T)) {
                .void => "None",
                .bool => "bool",
                .int => "int",
                .float => "float",
                .@"enum", .value, .@"union" => api.typeName(T),
                .handle => api.typeName(abi.HandleOf(T).?),
                .optional => hint(@typeInfo(T).optional.child) ++ " | None",
                .slice => "list[" ++ hint(@typeInfo(T).pointer.child) ++ "]",
                .string => "str",
                // Never a field nor a result.
                .buffer, .unsupported => unreachable,
            };
        }

        /// Type hint of a parameter: what the codec accepts, which is wider
        /// than `hint` for slices (any iterable, or a buffer), strings (bytes
        /// and paths too), buffers, and unions (a payload class used by one
        /// variant stands for that variant, see `_UnionAbi.by_type`).
        fn paramHint(comptime T: type) []const u8 {
            return switch (abi.kindOf(T)) {
                .optional => paramHint(@typeInfo(T).optional.child) ++ " | None",
                .slice => if (@typeInfo(T).pointer.child == u8) "_BytesLike" else "_Iterable[" ++ paramHint(@typeInfo(T).pointer.child) ++ "]",
                .buffer => "_Buffer",
                .string => "_StrLike",
                .@"union" => blk: {
                    var s: []const u8 = api.typeName(T);
                    const info = @typeInfo(T).@"union";
                    for (info.field_types) |F| {
                        if (abi.kindOf(F) != .value) continue;
                        var uses: usize = 0;
                        for (info.field_types) |other| uses += @intFromBool(other == F);
                        if (uses == 1) s = s ++ " | " ++ api.typeName(F);
                    }
                    break :blk s;
                },
                else => hint(T),
            };
        }

        /// Python literal of a comptime-known value.
        fn writeLiteral(w: *Writer, comptime T: type, comptime v: T) !void {
            switch (comptime abi.kindOf(T)) {
                .bool => try w.writeAll(if (v) "True" else "False"),
                .int => try w.print("{d}", .{v}),
                .float => if (std.math.isNan(v))
                    try w.writeAll("float(\"nan\")")
                else if (std.math.isInf(v))
                    try w.writeAll(if (v > 0) "float(\"inf\")" else "float(\"-inf\")")
                else
                    try w.writeAll(comptime floatLiteral(v)),
                .@"enum" => try w.print("{s}.{f}", .{ api.typeName(T), py(@tagName(v)) }),
                .value => {
                    try w.print("{s}(", .{api.typeName(T)});
                    inline for (@typeInfo(T).@"struct".field_names, @typeInfo(T).@"struct".field_types, 0..) |name, F, i| {
                        try w.print("{s}{f}=", .{ if (i > 0) ", " else "", py(name) });
                        try writeLiteral(w, F, @field(v, name));
                    }
                    try w.writeAll(")");
                },
                .@"union" => switch (v) {
                    inline else => |payload, tag| {
                        try w.print("{s}(\"{f}\"", .{ api.typeName(T), py(@tagName(tag)) });
                        if (@TypeOf(payload) != void) {
                            try w.writeAll(", ");
                            try writeLiteral(w, @TypeOf(payload), payload);
                        }
                        try w.writeAll(")");
                    },
                },
                .optional => if (v) |c| try writeLiteral(w, @TypeOf(c), c) else try w.writeAll("None"),
                else => unreachable,
            }
        }

        /// Python class holding a nested declared type as an attribute, e.g.
        /// `Source` for `Source.TwoSurface`.
        fn parentOf(comptime t: walk.Type) ?[]const u8 {
            const dot = std.mem.lastIndexOfScalar(u8, t.path, '.') orelse return null;
            for (api.types) |p| {
                if (std.mem.eql(u8, p.path, t.path[0..dot])) return p.name;
            }
            return null;
        }
    };
}

const Style = enum { function, method, init, static };

fn firstDefault(comptime params: []const type, comptime style: Style) usize {
    var first = params.len;
    while (first > 0 and canDefault(params[first - 1])) first -= 1;
    return if (style == .method and first == 0) 1 else first;
}

fn canDefault(comptime P: type) bool {
    return switch (abi.kindOf(P)) {
        .optional => true,
        .value => for (@typeInfo(P).@"struct".field_attrs) |attrs| {
            if (attrs.default_value_ptr == null) break false;
        } else true,
        else => false,
    };
}

/// ctypes type of a C integer, float or bool.
fn scalarCType(comptime C: type) []const u8 {
    const named = .{
        .{ bool, "c_bool" },     .{ c_short, "c_short" },       .{ c_ushort, "c_ushort" },
        .{ c_int, "c_int" },     .{ c_uint, "c_uint" },         .{ c_long, "c_long" },
        .{ c_ulong, "c_ulong" }, .{ c_longlong, "c_longlong" }, .{ c_ulonglong, "c_ulonglong" },
        .{ usize, "c_size_t" },  .{ isize, "c_ssize_t" },       .{ f32, "c_float" },
        .{ f64, "c_double" },
    };
    inline for (named) |n| if (C == n[0]) return "_c." ++ n[1];
    const info = @typeInfo(C).int;
    return std.fmt.comptimePrint("_c.c_{s}int{d}", .{ if (info.signedness == .unsigned) "u" else "", info.bits });
}

/// Whether a default needs `default_factory`: Python shares plain defaults
/// between instances.
fn isMutable(comptime T: type, comptime v: T) bool {
    return switch (abi.kindOf(T)) {
        .value, .@"union" => true,
        .optional => if (v) |c| isMutable(@TypeOf(c), c) else false,
        else => false,
    };
}

/// Shortest decimal form, always readable as a Python float.
fn floatLiteral(comptime v: anytype) []const u8 {
    const s = std.fmt.comptimePrint("{d}", .{v});
    for (s) |c| if (c == '.' or c == 'e') return s;
    return s ++ ".0";
}

fn writeString(w: *Writer, s: []const u8) !void {
    try w.writeByte('"');
    for (s) |c| switch (c) {
        '"', '\\' => try w.print("\\{c}", .{c}),
        '\n' => try w.writeAll("\\n"),
        else => try w.writeByte(c),
    };
    try w.writeByte('"');
}

fn writeDocstring(w: *Writer, doc: []const u8, indent: []const u8) !void {
    try w.print("{s}\"\"\"", .{indent});
    var lines = std.mem.splitScalar(u8, doc, '\n');
    var first = true;
    while (lines.next()) |line| {
        if (!first) {
            try w.writeAll("\n");
            if (line.len > 0) try w.writeAll(indent);
        }
        first = false;
        for (line) |c| switch (c) {
            '\\', '"' => try w.print("\\{c}", .{c}),
            else => try w.writeByte(c),
        };
    }
    if (std.mem.indexOfScalar(u8, doc, '\n') != null) try w.print("\n{s}", .{indent});
    try w.writeAll("\"\"\"\n");
}

fn lastSegment(comptime path: []const u8) []const u8 {
    const dot = std.mem.lastIndexOfScalar(u8, path, '.') orelse return path;
    return path[dot + 1 ..];
}

const keywords = [_][]const u8{
    "False",   "None",     "True",     "and",    "as",   "assert", "async",  "await",
    "break",   "class",    "continue", "def",    "del",  "elif",   "else",   "except",
    "finally", "for",      "from",     "global", "if",   "import", "in",     "is",
    "lambda",  "nonlocal", "not",      "or",     "pass", "raise",  "return", "try",
    "while",   "with",     "yield",
};

/// `name` as a Python identifier: a trailing underscore escapes keywords.
fn py(name: []const u8) PyName {
    return .{ .name = name };
}

const PyName = struct {
    name: []const u8,

    pub fn format(n: PyName, w: *Writer) Writer.Error!void {
        try w.writeAll(n.name);
        for (keywords) |k| if (std.mem.eql(u8, k, n.name)) return w.writeByte('_');
    }
};

/// "addVolume" -> "add_volume", "toCString" -> "to_c_string".
pub fn snakeCase(comptime name: []const u8) []const u8 {
    return comptime blk: {
        var out: []const u8 = "";
        for (name, 0..) |c, i| {
            if (std.ascii.isUpper(c) and i > 0 and name[i - 1] != '_') {
                const prev = name[i - 1];
                const next_lower = i + 1 < name.len and std.ascii.isLower(name[i + 1]);
                if (std.ascii.isLower(prev) or std.ascii.isDigit(prev) or (std.ascii.isUpper(prev) and next_lower)) {
                    out = out ++ "_";
                }
            }
            out = out ++ .{std.ascii.toLower(c)};
        }
        const final = out[0..out.len].*;
        break :blk &final;
    };
}

test snakeCase {
    try std.testing.expectEqualStrings("add_volume", comptime snakeCase("addVolume"));
    try std.testing.expectEqualStrings("from_axis_x", comptime snakeCase("fromAxisX"));
    try std.testing.expectEqualStrings("to_c_string", comptime snakeCase("toCString"));
    try std.testing.expectEqualStrings("http_server", comptime snakeCase("HTTPServer"));
    try std.testing.expectEqualStrings("init", comptime snakeCase("init"));
    try std.testing.expectEqualStrings("already_snake", comptime snakeCase("already_snake"));
}
